import { describe, expect, it } from "bun:test"
import { readFileSync } from "node:fs"
import {
  compareImageInputRecord,
  IMAGE_PROBE_CODE,
  imageProbeVerdict,
  renderImageInputModule,
} from "../scripts/probe-cursor-image-input.js"
import { CURSOR_IMAGE_INPUT } from "../src/image-input-data.js"
import { cursorModelReadsImages } from "../src/model-metadata.js"

describe("live image-input probe", () => {
  it("reads a transcribed probe code as image input and NO IMAGE as text only", () => {
    expect(IMAGE_PROBE_CODE).toBe("Q4X8-2756")
    for (const reply of ["Text: Q4X8-2756", "`q4x8 2756`", "**Q4X8–2756**", "Q4X8-2756\nNO IMAGE elsewhere"]) {
      expect(imageProbeVerdict(reply)).toBe(true)
    }
    for (const reply of ["NO IMAGE", "No image.", "no-image"]) expect(imageProbeVerdict(reply)).toBe(false)
    // Neither a transcription nor a refusal needs a person, not a guess.
    for (const reply of ["", "A red square, a blue circle and a green triangle.", "Q4X8-2757"]) {
      expect(imageProbeVerdict(reply)).toBeUndefined()
    }
  })

  it("lists untested live models and recorded models Cursor no longer lists", () => {
    expect(compareImageInputRecord(["b", "a", "toString", "c"], { c: false, a: true, retired: true })).toEqual({
      missing: ["b", "toString"],
      stale: ["retired"],
    })
    expect(compareImageInputRecord([], {})).toEqual({ missing: [], stale: [] })
  })

  it("renders a sorted generated module that the committed record matches", () => {
    const rendered = renderImageInputModule({ zeta: false, alpha: true })
    expect(rendered).toStartWith("/**\n * AUTO-GENERATED by scripts/probe-cursor-image-input.ts")
    expect(rendered).toEndWith('export const CURSOR_IMAGE_INPUT = {\n  "alpha": true,\n  "zeta": false\n} as const\n')
    const committed = readFileSync(new URL("../src/image-input-data.ts", import.meta.url), "utf8")
    expect(committed).toBe(renderImageInputModule(CURSOR_IMAGE_INPUT))
    for (const value of Object.values(CURSOR_IMAGE_INPUT)) expect(typeof value).toBe("boolean")
  })

  it("advertises image input only for a model recorded as reading images", () => {
    const record = CURSOR_IMAGE_INPUT as Record<string, boolean>
    for (const [id, reads] of Object.entries(record)) expect(cursorModelReadsImages(id)).toBe(reads)
    for (const id of ["unrecorded-model", "toString", "__proto__", ""]) expect(cursorModelReadsImages(id)).toBe(false)
  })
})
