import { describe, expect, it } from "bun:test"
import { readFileSync } from "node:fs"
import {
  compareImageInputRecord,
  IMAGE_PROBE_CODE,
  imageProbeVerdict,
  planImageProbe,
  probeFailureReport,
  renderImageInputModule,
  staleNotice,
} from "../scripts/probe-cursor-image-input.js"
import { CURSOR_IMAGE_INPUT } from "../src/image-input-data.js"
import { cursorModelReadsImages } from "../src/model-metadata.js"

describe("live image-input probe", () => {
  it("reads a transcribed probe code as image input and NO IMAGE as text only", () => {
    expect(IMAGE_PROBE_CODE).toBe("Q4X8-2756")
    for (const reply of ["Text: Q4X8-2756", "`q4x8 2756`", "**Q4X8–2756**", "Q4X8-2756\nNO IMAGE elsewhere"]) {
      expect(imageProbeVerdict(reply)).toBe(true)
    }
    for (const reply of ["NO IMAGE", "No image.", "no-image", " NO IMAGE\n"]) expect(imageProbeVerdict(reply)).toBe(false)
    // Neither a transcription nor exactly the requested refusal records nothing.
    for (const reply of [
      "", "A red square, a blue circle and a green triangle.", "Q4X8-2757",
      "Red square. NO IMAGE is what I would say if the pixels were missing.",
      "NO IMAGE. Actually I can see a red square.",
    ]) {
      expect(imageProbeVerdict(reply)).toBeUndefined()
    }
  })

  it("lists untested live models and recorded models Cursor no longer lists", () => {
    expect(compareImageInputRecord(["b", "a", "toString", "c"], { c: false, a: true, retired: true })).toEqual({
      missing: ["b", "toString"],
      stale: ["retired"],
    })
    expect(compareImageInputRecord([], {})).toEqual({ missing: [], stale: [] })
  })

  it("never changes the record from an empty or partial live list unless asked to prune", () => {
    const committed = { kept: true, retired: false, other: true }
    expect(() => planImageProbe([], committed, { all: false, prune: true, models: [] }))
      .toThrow("AvailableModels listed no models; the record is unchanged")
    expect(planImageProbe(["kept"], committed, { all: false, prune: false, models: [] })).toEqual({
      targets: [], record: committed, missing: [], stale: ["other", "retired"],
    })
    expect(planImageProbe(["kept", "new"], committed, { all: false, prune: true, models: [] })).toEqual({
      targets: ["new"], record: { kept: true }, missing: ["new"], stale: ["other", "retired"],
    })
    expect(committed).toEqual({ kept: true, retired: false, other: true })
  })

  it("retests recorded models only on request", () => {
    const committed = { a: true, b: false }
    expect(planImageProbe(["a", "b", "c"], committed, { all: false, prune: false, models: [] }).targets).toEqual(["c"])
    expect(planImageProbe(["a", "b", "c"], committed, { all: false, prune: false, models: ["b", "c"] }).targets)
      .toEqual(["c", "b"])
    expect(planImageProbe(["a", "b", "c"], committed, { all: true, prune: false, models: [] }).targets)
      .toEqual(["a", "b", "c"])
    expect(() => planImageProbe(["a"], committed, { all: false, prune: false, models: ["gone"] }))
      .toThrow("Not in Cursor's live model list: gone")
  })

  it("reports a failed retest as keeping its result, and only an untested model as tried again", () => {
    const committed = { recorded: true }
    expect(probeFailureReport([
      { id: "recorded", reason: "capacity_limit" },
      { id: "fresh", reason: "unclear reply \"...\"" },
    ], committed)).toEqual([
      "Not recorded; the next run probes them again:",
      "  fresh: unclear reply \"...\"",
      "Kept the previous result; retest with --model <id>:",
      "  recorded: capacity_limit",
    ])
    // The next default run plans no retest for the kept id.
    expect(planImageProbe(["recorded", "fresh"], committed, { all: false, prune: false, models: [] }).targets)
      .toEqual(["fresh"])
    expect(probeFailureReport([], committed)).toEqual([])
  })

  it("claims removed stale ids only when a prune actually writes", () => {
    expect(staleNotice([], { check: false, prune: true })).toBeUndefined()
    expect(staleNotice(["old"], { check: false, prune: true }))
      .toBe("Recorded models this account does not list (removed): old")
    for (const options of [{ check: true, prune: true }, { check: false, prune: false }]) {
      expect(staleNotice(["old", "older"], options)).toBe("Recorded models this account does not list: old, older")
    }
  })

  it("renders a sorted generated module that the committed record matches", () => {
    const rendered = renderImageInputModule({ zeta: false, alpha: true })
    expect(rendered).toStartWith("/**\n * AUTO-GENERATED by scripts/probe-cursor-image-input.ts")
    expect(rendered).toEndWith('export const CURSOR_IMAGE_INPUT = {\n  "alpha": true,\n  "zeta": false\n} as const\n')
    const committed = readFileSync(new URL("../src/image-input-data.ts", import.meta.url), "utf8")
    expect(committed).toBe(renderImageInputModule(CURSOR_IMAGE_INPUT))
    for (const value of Object.values(CURSOR_IMAGE_INPUT)) expect(typeof value).toBe("boolean")
  })

  it("advertises image input only for a model recorded as reading images", () => {
    const record = CURSOR_IMAGE_INPUT as Record<string, boolean>
    for (const [id, reads] of Object.entries(record)) expect(cursorModelReadsImages(id)).toBe(reads)
    for (const id of ["unrecorded-model", "toString", "__proto__", ""]) expect(cursorModelReadsImages(id)).toBe(false)
  })
})
