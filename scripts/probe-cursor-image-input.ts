#!/usr/bin/env bun
/**
 * Live-test which Cursor models read image input and regenerate
 * src/image-input-data.ts. The catalog advertises image input only where this
 * probe saw the model read the image; Cursor's AvailableModels flag is wrong
 * for some models, and its Run drops images for a model that cannot read them.
 *
 * By default a model is probed once, when it first appears in Cursor's live
 * list: one short Run on its default variant with a fixture image whose text
 * appears nowhere else. A Run that fails or answers unclearly records nothing,
 * so the next run probes that model again. `--model` and `--all` retest
 * recorded models on request. Needs a Cursor credential: `CURSOR_API_KEY`,
 * else the browser login OpenCode stored.
 *
 *   bun run generate:images                   # probe newly listed models only
 *   bun run generate:images -- --model <id>   # retest these ids (repeatable)
 *   bun run generate:images -- --all          # retest every live model
 *   bun run generate:images -- --check        # fail if live models and the record differ
 */

import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import os from "node:os"
import path from "node:path"
import type { LanguageModelV3CallOptions } from "@ai-sdk/provider"
import { CURSOR_IMAGE_INPUT } from "../src/image-input-data.js"
import { createCursor } from "../src/index.js"
import { readStoredAuth } from "../src/context/auth-store.js"
import { getHostCacheDirOverride, setHostCacheDirOverride } from "../src/context/paths.js"
import { resolveBearerToken } from "../src/auth-renewal.js"
import { settleRunSavesForTests } from "../src/language-model.js"
import { fetchModels, writeCache } from "../src/models.js"
import { sessionManager } from "../src/session.js"
import { MODEL_CACHE_SCHEMA_VERSION } from "../src/shared.js"

/** The text drawn in the probe image; a model that cannot see it cannot guess it. */
export const IMAGE_PROBE_CODE = "Q4X8-2756"

export const IMAGE_PROBE_QUESTION =
  "Look at the attached image. List each shape with its color, then transcribe any text in it exactly. " +
  "If there is no image or you cannot see its pixels, reply exactly: NO IMAGE."

const PROBE_TIMEOUT_MS = 180_000

export type ImageInputRecord = Record<string, boolean>

/**
 * `true` when the reply transcribes the probe code, `false` when it says it
 * sees no image, `undefined` when the reply is neither and needs a person.
 */
export function imageProbeVerdict(reply: string): boolean | undefined {
  const compact = reply.toUpperCase().replace(/[^A-Z0-9]/g, "")
  if (compact.includes(IMAGE_PROBE_CODE.replace(/[^A-Z0-9]/g, ""))) return true
  if (compact.includes("NOIMAGE")) return false
  return undefined
}

/** Live ids without a result, and recorded ids Cursor no longer lists. */
export function compareImageInputRecord(
  liveIds: readonly string[],
  record: ImageInputRecord,
): { missing: string[]; stale: string[] } {
  const live = new Set(liveIds)
  return {
    missing: [...live].filter((id) => !Object.hasOwn(record, id)).sort(),
    stale: Object.keys(record).filter((id) => !live.has(id)).sort(),
  }
}

export function renderImageInputModule(record: ImageInputRecord): string {
  const sorted = Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)))
  return `/**
 * AUTO-GENERATED by scripts/probe-cursor-image-input.ts — do not edit by hand.
 * Whether a Cursor model's Run read the probe image: true advertises image
 * input; false, or a model missing here, advertises text only.
 * Regenerate: bun run generate:images
 */

export const CURSOR_IMAGE_INPUT = ${JSON.stringify(sorted, null, 2)} as const
`
}

type Options = { check: boolean; all: boolean; models: string[] }

function parseArgs(argv: string[]): Options {
  const options: Options = { check: false, all: false, models: [] }
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]!
    if (arg === "--check") options.check = true
    else if (arg === "--all") options.all = true
    else if (arg === "--model" && argv[i + 1]) options.models.push(argv[++i]!)
    else throw new Error(`Unknown argument: ${arg}`)
  }
  return options
}

async function credential(): Promise<{ accessToken: string } | { apiKey: string }> {
  const apiKey = process.env.CURSOR_API_KEY
  if (apiKey) return { apiKey }
  const stored = await readStoredAuth("cursor")
  if (stored?.type === "api") return { apiKey: stored.key }
  if (stored?.type === "oauth") {
    // Renewing here would rotate the stored login without saving it.
    if (stored.expires <= Date.now()) throw new Error("The stored Cursor login has expired; sign in to Cursor in OpenCode again")
    return { accessToken: stored.access }
  }
  throw new Error("No Cursor credential: set CURSOR_API_KEY or sign in to Cursor in OpenCode")
}

async function probe(
  model: ReturnType<ReturnType<typeof createCursor>["languageModel"]>,
  id: string,
  image: Uint8Array,
): Promise<{ reply: string; error?: string }> {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), PROBE_TIMEOUT_MS)
  let reply = ""
  try {
    const { stream } = await model.doStream({
      prompt: [{ role: "user", content: [
        { type: "text", text: IMAGE_PROBE_QUESTION },
        { type: "file", mediaType: "image/png", filename: "probe.png", data: image },
      ] }],
      headers: { "x-opencode-session-id": `ses_image_probe_${id}_${Date.now()}` },
      abortSignal: controller.signal,
    } as LanguageModelV3CallOptions)
    const reader = stream.getReader()
    for (;;) {
      const { done, value } = await reader.read()
      if (done) break
      if (value.type === "text-delta") reply += value.delta
      if (value.type === "error") return { reply, error: String((value.error as Error)?.message ?? value.error) }
    }
    return { reply }
  } catch (error) {
    return { reply, error: error instanceof Error ? error.message : String(error) }
  } finally {
    clearTimeout(timer)
  }
}

async function main(): Promise<void> {
  const options = parseArgs(process.argv.slice(2))
  const auth = await credential()
  const token = await resolveBearerToken(auth)
  const liveModels = await fetchModels(token)
  const liveIds = liveModels.map((model) => model.id)
  const record: ImageInputRecord = { ...CURSOR_IMAGE_INPUT }
  const { missing, stale } = compareImageInputRecord(liveIds, record)

  if (options.check) {
    if (missing.length || stale.length) {
      if (missing.length) console.error(`Untested Cursor models: ${missing.join(", ")}`)
      if (stale.length) console.error(`Recorded models Cursor no longer lists: ${stale.join(", ")}`)
      console.error("Run: bun run generate:images")
      process.exit(1)
    }
    console.log(`OK: ${liveIds.length} live models; image-input-data.ts up to date`)
    return
  }

  const unknown = options.models.filter((id) => !liveIds.includes(id))
  if (unknown.length) throw new Error(`Not in Cursor's live model list: ${unknown.join(", ")}`)
  const targets = options.all ? liveIds : [...new Set([...missing, ...options.models])]
  for (const id of stale) delete record[id]

  const image = new Uint8Array(await readFile(new URL("../test/fixtures/image-probe.png", import.meta.url)))
  const cacheDir = await mkdtemp(path.join(os.tmpdir(), "cursor-image-probe-"))
  const previousCache = getHostCacheDirOverride()
  const failures: string[] = []
  try {
    await writeCache(cacheDir, { schemaVersion: MODEL_CACHE_SCHEMA_VERSION, fetchedAt: Date.now(), models: liveModels })
    const cursor = createCursor({ name: "cursor", ...auth, cacheDir })
    for (const id of targets) {
      const { reply, error } = await probe(cursor.languageModel(id), id, image)
      const verdict = error ? undefined : imageProbeVerdict(reply)
      if (verdict === undefined) {
        failures.push(`${id}: ${error ?? `unclear reply ${JSON.stringify(reply.trim().slice(0, 300))}`}`)
        continue
      }
      record[id] = verdict
      console.log(`${id}: ${verdict ? "reads images" : "text only"}`)
    }
  } finally {
    sessionManager.dispose()
    await settleRunSavesForTests()
    setHostCacheDirOverride(previousCache)
    await rm(cacheDir, { recursive: true, force: true })
  }

  const dest = path.join(import.meta.dir, "..", "src", "image-input-data.ts")
  await writeFile(dest, renderImageInputModule(record))
  console.log(`Wrote src/image-input-data.ts (${Object.keys(record).length} models; ${stale.length} removed)`)
  if (failures.length) {
    console.error(`Not recorded; the next run probes them again:\n  ${failures.join("\n  ")}`)
    process.exit(1)
  }
}

if (import.meta.main) {
  main().then(() => process.exit(0), (error) => {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  })
}
