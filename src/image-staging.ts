/**
 * Staging for images Cursor generated server-side.
 *
 * Cursor's GenerateImage runs on its servers and hands the client finished
 * bytes. OpenCode's `write` tool takes a string and additionally BOM-splits,
 * diffs, and runs `Format.file()` on what it writes, so image bytes cannot pass
 * through it — the bytes have to be written by provider code.
 *
 * That write still must raise OpenCode's permission, and `ctx.ask` is only
 * reachable inside a plugin tool's `execute`. So the bytes wait here, keyed by
 * a single-use id, and the tool that commits them takes only that id: no path
 * and no content ever crosses the tool boundary. A tool visible in the catalog
 * therefore cannot be used to write arbitrary bytes anywhere — it can only
 * commit an image this provider already received, or do nothing.
 *
 * Approach adapted from jkalasas/opencode-antigravity-image (MIT), which
 * established writing image bytes from inside a plugin tool rather than through
 * the host's text `write`. No code was copied; the permission gate, the
 * handle-only tool surface, and the containment checks are this provider's.
 */

import { randomUUID } from "node:crypto"
import fs from "node:fs"
import path from "node:path"

export type PendingCursorImage = {
  id: string
  /** Absolute target, already remapped onto a real location under this host. */
  path: string
  /** Host project folder the target was mapped into; an allowed write root. */
  projectDir?: string
  mime: string
  data: Uint8Array
  /** OpenCode session that may commit this image. */
  sessionId?: string
  createdAt: number
}

export type StageCursorImageInput = {
  path: string
  projectDir?: string
  mime: string
  data: Uint8Array
  sessionId?: string
}

/** Cursor's own edit ceiling is 50 MB; images are far smaller in practice. */
export const MAX_STAGED_IMAGE_BYTES = 50 * 1024 * 1024
/** A staged image is committed within one tool round-trip or it is stale. */
export const STAGED_IMAGE_TTL_MS = 10 * 60_000
/** Bounds memory if a turn generates several images and none are committed. */
const MAX_PENDING = 8

// Some hosts load the model and the image-save subpath in separate module
// graphs. Keep the one-use handles in the process registry so both graphs see
// the same staged bytes. The UUID handle remains the only tool input.
const PENDING_IMAGES = Symbol.for("cursor-opencode-provider.pending-images")
const SAVING_IMAGES = Symbol.for("cursor-opencode-provider.saving-images")
const globals = globalThis as typeof globalThis & {
  [PENDING_IMAGES]?: Map<string, PendingCursorImage>
  [SAVING_IMAGES]?: Map<string, PendingCursorImage>
}
const pending = globals[PENDING_IMAGES] ??= new Map<string, PendingCursorImage>()
/** Claimed images whose save, permission wait included, has not finished; they keep their path. */
const saving = globals[SAVING_IMAGES] ??= new Map<string, PendingCursorImage>()

export class StagedImageTooLargeError extends Error {
  constructor(bytes: number) {
    super(`Generated image is ${bytes} bytes, above the ${MAX_STAGED_IMAGE_BYTES} byte limit`)
    this.name = "StagedImageTooLargeError"
  }
}

function prune(now: number): void {
  for (const [id, image] of pending) {
    if (now - image.createdAt > STAGED_IMAGE_TTL_MS) pending.delete(id)
  }
  // Oldest-first eviction: Map preserves insertion order and ids are only ever
  // appended, so the first entries are the oldest.
  while (pending.size >= MAX_PENDING) {
    const oldest = pending.keys().next().value
    if (oldest === undefined) break
    pending.delete(oldest)
  }
}

/** Hold generated bytes and return the handle the commit tool will be given. */
export function stageCursorImage(input: StageCursorImageInput, now = Date.now()): string {
  if (input.data.length > MAX_STAGED_IMAGE_BYTES) {
    throw new StagedImageTooLargeError(input.data.length)
  }
  prune(now)
  const id = `cursor-image-${randomUUID()}`
  pending.set(id, {
    id,
    path: input.path,
    projectDir: input.projectDir,
    mime: input.mime,
    data: input.data,
    sessionId: input.sessionId,
    createdAt: now,
  })
  return id
}

/**
 * Claim a staged image. Single use: a replayed or guessed id finds nothing, so
 * the commit tool cannot be driven twice or by a caller that never had a real
 * handle. The claimed image keeps its path reserved until
 * {@link finishCursorImageSave}.
 */
export function takePendingCursorImage(
  id: string,
  now = Date.now(),
): PendingCursorImage | undefined {
  const image = pending.get(id)
  if (!image) return undefined
  pending.delete(id)
  if (now - image.createdAt > STAGED_IMAGE_TTL_MS) return undefined
  saving.set(id, image)
  return image
}

/** The save of a claimed image ended, written or not; its path is free again. */
export function finishCursorImageSave(id: string): void {
  saving.delete(id)
}

function sameBytes(a: Uint8Array, b: Uint8Array): boolean {
  return a.length === b.length && Buffer.from(a.buffer, a.byteOffset, a.length)
    .equals(Buffer.from(b.buffer, b.byteOffset, b.length))
}

/** Whether `target` is free for `data`: absent, or already holding those bytes. */
function holdsOnlyBytes(target: string, data: Uint8Array): boolean {
  for (const image of [...pending.values(), ...saving.values()]) {
    if (image.path === target && !sameBytes(image.data, data)) return false
  }
  let stat: fs.Stats
  try {
    stat = fs.lstatSync(target)
  } catch {
    return true
  }
  // A link or directory is never overwritten through; the save refuses links.
  if (!stat.isFile()) return false
  if (stat.size !== data.length) return false
  try {
    return sameBytes(fs.readFileSync(target), data)
  } catch {
    return false
  }
}

/** Names tried beside a taken one before an image is refused rather than overwrite a file. */
const MAX_DISTINCT_NAMES = 100

/**
 * A Run's input images often share a file name (three different `cvs.png`).
 * Cursor writes each to `assets/<name>`, so the later ones would replace the
 * earlier. Keep an image whose name is taken by other bytes, on disk, staged or
 * being saved, beside it as `<name>-<hash12><ext>`, or `<name>-<hash12>-<n><ext>`
 * when that is taken too; the WriteResult reports that path.
 */
export function distinctInputImagePath(target: string, data: Uint8Array, hash: string): string {
  if (holdsOnlyBytes(target, data)) return target
  const extension = path.extname(target)
  const stem = `${target.slice(0, target.length - extension.length)}-${hash.slice(0, 12)}`
  for (let n = 1; n <= MAX_DISTINCT_NAMES; n++) {
    const candidate = `${stem}${n === 1 ? "" : `-${n}`}${extension}`
    if (holdsOnlyBytes(candidate, data)) return candidate
  }
  throw new Error(`No free name for the image beside ${target}; nothing was overwritten.`)
}

/** Drop a staged image whose turn ended without committing it. */
export function discardPendingCursorImage(id: string): void {
  pending.delete(id)
}

/** Test seam. */
export function clearPendingCursorImages(): void {
  pending.clear()
  saving.clear()
}

export function pendingCursorImageCount(): number {
  return pending.size
}
